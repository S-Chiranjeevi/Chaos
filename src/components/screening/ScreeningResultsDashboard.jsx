import React, { useState } from 'react';
import {
  AlertTriangle,
  ArrowLeft,
  CheckCircle2,
  Clipboard,
  Download,
  Scale,
  Stethoscope,
  Activity,
  FileText
} from 'lucide-react';

export function ScreeningResultsDashboard({ result, inputs, onReset }) {
  const [copied, setCopied] = useState(false);

  if (!result) return null;

  const isElevated = result.prediction === 1 || result.prediction_label === 'Elevated Risk';
  const probabilityPercent = (result.probability * 100).toFixed(1);

  // Format a text summary suitable for doctor consultation
  const generateDoctorSummary = () => {
    return `=== LUNAHER PATTERN SCREENING SUMMARY ===
Date: ${new Date().toLocaleDateString()}
Analysis Mode: ${result.analysis_mode === 'hybrid' ? 'Clinical Parameters + Ultrasound Estimate' : 'Clinical Parameters Only'}
Screening Model: LunaHer Pattern Screening Model v1.0.0
Screening Result: ${result.prediction_label}
Model Output Score: ${probabilityPercent}% (Uncalibrated Research Score)

CALCULATED METRICS:
- BMI: ${result.calculated_metrics?.bmi ?? 'N/A'} kg/m²
- Waist-to-Hip Ratio: ${result.calculated_metrics?.waist_hip_ratio ?? 'N/A'}

RELEVANT CLINICAL PARAMETERS ENTERED:
- Age: ${inputs.age ?? 'N/A'} yrs
- Cycle History: ${inputs.cycle_regularity === 2 ? 'Regular' : inputs.cycle_regularity === 4 ? 'Irregular' : 'N/A'} (Length: ${inputs.cycle_length_days ?? 'N/A'} days)
- Weight Gain: ${inputs.weight_gain ? 'Yes' : 'No'}
- Excess Hair Growth (Hirsutism): ${inputs.hair_growth ? 'Yes' : 'No'}
- Skin Darkening (Acanthosis Nigricans): ${inputs.skin_darkening ? 'Yes' : 'No'}
- Pimples / Acne: ${inputs.pimples ? 'Yes' : 'No'}
- Hair Thinning: ${inputs.hair_loss ? 'Yes' : 'No'}
${inputs.follicle_no_left != null ? `- Left Follicles: ${inputs.follicle_no_left}` : ''}
${inputs.follicle_no_right != null ? `- Right Follicles: ${inputs.follicle_no_right}` : ''}
${inputs.amh != null ? `- AMH: ${inputs.amh} ng/mL` : ''}
${inputs.fsh != null ? `- FSH: ${inputs.fsh} mIU/mL` : ''}
${inputs.lh != null ? `- LH: ${inputs.lh} mIU/mL` : ''}
${inputs.tsh != null ? `- TSH: ${inputs.tsh} mIU/L` : ''}

CLINICAL DISCLAIMER:
This summary was generated by a research machine learning screening tool for educational and discussion purposes only. It is NOT a medical diagnosis or treatment plan. Formal diagnosis of PCOS requires clinical evaluation by a licensed healthcare professional using established diagnostic standards (e.g. Rotterdam Criteria).
`;
  };

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(generateDoctorSummary());
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback
      setCopied(false);
    }
  };

  const handleDownload = () => {
    const text = generateDoctorSummary();
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `pcos-research-screening-${new Date().toISOString().split('T')[0]}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="screening-results-dashboard space-y-6" data-testid="screening-results">
      {/* Top Banner / Outcome */}
      <div
        className={`p-6 rounded-2xl border-2 transition-all shadow-sm ${
          isElevated
            ? 'bg-rose-50 border-rose-300 text-rose-950'
            : 'bg-emerald-50 border-emerald-300 text-emerald-950'
        }`}
      >
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            {isElevated ? (
              <div className="p-3 bg-rose-200 text-rose-800 rounded-xl shadow-xs">
                <AlertTriangle size={28} aria-hidden="true" />
              </div>
            ) : (
              <div className="p-3 bg-emerald-200 text-emerald-800 rounded-xl shadow-xs">
                <CheckCircle2 size={28} aria-hidden="true" />
              </div>
            )}
            <div>
              <span className="text-xs uppercase tracking-wider font-bold text-stone-600 block">
                Model Classification Outcome
              </span>
              <h2 className="text-2xl sm:text-3xl font-extrabold tracking-tight mt-0.5 text-stone-900">
                {result.prediction_label}
              </h2>
            </div>
          </div>

          <div className="text-left sm:text-right bg-white px-5 py-3 rounded-xl border-2 border-stone-200 shadow-xs">
            <span className="text-xs text-stone-600 font-bold uppercase tracking-wider block">
              Experimental Score
            </span>
            <span className="text-2xl sm:text-3xl font-black font-mono tracking-tight text-stone-900">
              {probabilityPercent}%
            </span>
          </div>
        </div>

        <p className="mt-4 text-sm leading-relaxed text-stone-800 font-medium">
          {result.screening_summary}
        </p>
      </div>


      {/* Derived Physical Metrics */}
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
        <div className="p-5 bg-white rounded-2xl border border-stone-200 shadow-sm">
          <div className="flex items-center gap-2 text-stone-600 text-xs font-bold uppercase tracking-wider mb-1">
            <Scale size={18} className="text-teal-700" />
            <span>Body Mass Index (BMI)</span>
          </div>
          <div className="flex items-baseline gap-2 mt-1">
            <span className="text-3xl font-extrabold text-stone-900 font-mono">
              {result.calculated_metrics?.bmi ?? 'N/A'}
            </span>
            <span className="text-xs font-semibold text-stone-500">kg/m²</span>
          </div>
          <p className="text-xs text-stone-600 mt-2 font-medium">
            Auto-derived from Height ({inputs.height_cm} cm) and Weight ({inputs.weight_kg} kg).
          </p>
        </div>

        <div className="p-5 bg-white rounded-2xl border border-stone-200 shadow-sm">
          <div className="flex items-center gap-2 text-stone-600 text-xs font-bold uppercase tracking-wider mb-1">
            <Activity size={18} className="text-teal-700" />
            <span>Waist-to-Hip Ratio</span>
          </div>
          <div className="flex items-baseline gap-2 mt-1">
            <span className="text-3xl font-extrabold text-stone-900 font-mono">
              {result.calculated_metrics?.waist_hip_ratio ?? 'N/A'}
            </span>
          </div>
          <p className="text-xs text-stone-600 mt-2 font-medium">
            Auto-derived from Waist ({inputs.waist_inch}&quot;) and Hip ({inputs.hip_inch}&quot;). WHO healthy threshold is &le; 0.85.
          </p>
        </div>
      </div>

      {/* Feature Comparison vs Research Cohort */}
      {result.contributing_features && result.contributing_features.length > 0 && (
        <div className="bg-white rounded-2xl border border-stone-200 p-5 shadow-sm">
          <h3 className="text-base font-bold text-stone-900 mb-2 flex items-center gap-2">
            <FileText size={18} className="text-teal-700" />
            <span>Key Model Predictor Comparison</span>
          </h3>
          <p className="text-xs text-stone-600 mb-4 font-medium">
            Comparison of your submitted parameters against the model’s reference values:
          </p>

          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs border-collapse">
              <thead>
                <tr className="border-b border-stone-200 text-stone-600 uppercase tracking-wider font-bold bg-stone-50">
                  <th className="py-2.5 px-3">Predictor Feature</th>
                  <th className="py-2.5 px-3">Your Value</th>
                  <th className="py-2.5 px-3">Dataset Median</th>
                  <th className="py-2.5 px-3">Model Importance</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-stone-100 text-stone-800">
                {result.contributing_features.map((feat, idx) => (
                  <tr key={idx} className="hover:bg-stone-50 transition-colors">
                    <td className="py-2.5 px-3 font-semibold text-stone-900">
                      {feat.feature}
                    </td>
                    <td className="py-2.5 px-3 font-bold text-stone-900">
                      {feat.patient_value != null ? feat.patient_value : 'Not provided'}
                    </td>
                    <td className="py-2.5 px-3 text-stone-600 font-medium">
                      {feat.cohort_median != null ? feat.cohort_median : '—'}
                    </td>
                    <td className="py-2.5 px-3 text-stone-600 font-medium">
                      {feat.importance_rank ? `#${feat.importance_rank} by gain` : '—'}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Rotterdam Criteria Context */}
      <div className="bg-white rounded-2xl border border-stone-200 p-6 shadow-sm">
        <h3 className="text-base font-bold text-stone-900 flex items-center gap-2 mb-2">
          <Stethoscope size={20} className="text-teal-700" />
          <span>Understanding Clinical Diagnosis: The Rotterdam Criteria</span>
        </h3>
        <p className="text-xs sm:text-sm text-stone-700 leading-relaxed mb-3 font-medium">
          Machine learning algorithms can flag statistical patterns, but licensed medical providers diagnose PCOS according to international consensus guidelines (such as the <strong className="text-stone-900 font-bold">Rotterdam Consensus 2003</strong>), which requires meeting at least <strong className="text-stone-900 font-bold">two out of three</strong> criteria after excluding other endocrine conditions:
        </p>
        <ul className="text-xs sm:text-sm text-stone-800 space-y-2 list-disc pl-5 font-normal">
          <li><strong className="text-stone-900 font-bold">Oligo- or anovulation:</strong> Irregular, infrequent, or absent menstrual cycles.</li>
          <li><strong className="text-stone-900 font-bold">Hyperandrogenism:</strong> Clinical signs (excess facial/body hair, persistent adult acne, androgenic alopecia) or biochemical markers (elevated serum testosterone or DHEA-S).</li>
          <li><strong className="text-stone-900 font-bold">Polycystic ovarian morphology:</strong> Presence of &ge; 12–20 follicles per ovary or ovarian volume &gt; 10 mL on pelvic ultrasound.</li>
        </ul>
      </div>

      {/* Separation Notice */}
      <div className="p-4 bg-stone-50 rounded-xl border border-stone-200 text-stone-700 text-xs sm:text-sm leading-relaxed">
        <strong className="text-stone-900 font-bold">Feature Independence:</strong> This research screening operates strictly independently of LunaHer’s APIVerve menstrual cycle forecasting and daily symptom journal. A predicted cycle date is not a PCOS diagnosis, and this ML score does not predict cycle lengths.
      </div>

      {/* Action Buttons */}
      <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
        <button
          type="button"
          onClick={onReset}
          className="px-4 py-2.5 text-xs sm:text-sm font-semibold text-stone-800 hover:text-stone-950 bg-white hover:bg-stone-50 border border-stone-300 rounded-xl shadow-xs transition-colors flex items-center gap-2 cursor-pointer"
        >
          <ArrowLeft size={16} />
          <span>Adjust Parameters or Run Again</span>
        </button>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleCopy}
            className="px-4 py-2.5 text-xs sm:text-sm font-semibold text-stone-800 hover:text-stone-950 bg-white hover:bg-stone-50 border border-stone-300 rounded-xl shadow-xs transition-colors flex items-center gap-2 cursor-pointer"
          >
            <Clipboard size={16} />
            <span>{copied ? 'Copied to Clipboard!' : 'Copy Summary for Doctor'}</span>
          </button>

          <button
            type="button"
            onClick={handleDownload}
            className="px-4 py-2.5 text-xs sm:text-sm font-bold text-white bg-teal-700 hover:bg-teal-800 rounded-xl shadow-xs transition-colors flex items-center gap-2 cursor-pointer"
          >
            <Download size={16} />
            <span>Download .txt Summary</span>
          </button>
        </div>
      </div>
    </div>
  );
}

export default ScreeningResultsDashboard;
